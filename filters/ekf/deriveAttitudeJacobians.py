"""Derive the attitude-EKF models and Jacobians symbolically and write MATLAB code.

Run from anywhere:  python3 filters/ekf/deriveAttitudeJacobians.py
Writes attitudeProcess.m and attitudeMeasurement.m next to this script.
Conventions match sensors/measurementModel.m and plant/rot*.m:
R_IB = Rz(psi) Ry(theta) Rx(phi), omega = W_eta * deta.
"""
from pathlib import Path

import sympy as sp

phi, theta, psi, Ts = sp.symbols('phi theta psi Ts', real=True)
wx, wy, wz = sp.symbols('omega1 omega2 omega3', real=True)
gx, gy, gz, mx, my, mz = sp.symbols('g_I1 g_I2 g_I3 m_I1 m_I2 m_I3', real=True)
eta = sp.Matrix([phi, theta, psi])
omega = sp.Matrix([wx, wy, wz])
g_I = sp.Matrix([gx, gy, gz])
m_I = sp.Matrix([mx, my, mz])


def rotx(a):
    return sp.Matrix([[1, 0, 0], [0, sp.cos(a), -sp.sin(a)], [0, sp.sin(a), sp.cos(a)]])


def roty(a):
    return sp.Matrix([[sp.cos(a), 0, sp.sin(a)], [0, 1, 0], [-sp.sin(a), 0, sp.cos(a)]])


def rotz(a):
    return sp.Matrix([[sp.cos(a), -sp.sin(a), 0], [sp.sin(a), sp.cos(a), 0], [0, 0, 1]])


W = sp.Matrix([[1, 0, -sp.sin(theta)],
               [0, sp.cos(phi), sp.sin(phi) * sp.cos(theta)],
               [0, -sp.sin(phi), sp.cos(phi) * sp.cos(theta)]])
Winv = sp.simplify(W.inv())
R_IB = rotz(psi) * roty(theta) * rotx(phi)

G = Ts * Winv                       # d eta1 / d omega
eta1 = eta + G * omega              # Euler step, same as the plant integrator
F = eta1.jacobian(eta)
h = sp.Matrix.vstack(R_IB.T * (-g_I), R_IB.T * m_I)   # accelerometer (xi_dd = 0); magnetometer
H = h.jacobian(eta)


def emit(name, signature, doc, outputs, inputs):
    """Write a MATLAB function with common subexpressions factored out."""
    exprs = [sp.simplify(e) for _, e in outputs]
    subs, reduced = sp.cse(exprs, symbols=sp.numbered_symbols('t'))
    lines = [f'function {signature}', *[f'%{d}' for d in doc],
             '% Generated by deriveAttitudeJacobians.py - do not edit by hand.']
    lines += [f'{s} = {v};' for s, v in inputs]
    lines += [f'{sp.octave_code(v, assign_to=str(s))}' for s, v in subs]
    for (out, _), e in zip(outputs, reduced):
        lines.append(sp.octave_code(e, assign_to=out))
    lines.append('end')
    path = Path(__file__).with_name(f'{name}.m')
    path.write_text('\n'.join(lines) + '\n')
    print(f'wrote {path}')


angles = [('phi', 'eta(1)'), ('theta', 'eta(2)'), ('psi', 'eta(3)')]
emit('attitudeProcess', '[eta1, F, G] = attitudeProcess(eta, omega, Ts)',
     ['ATTITUDEPROCESS Euler step eta1 = eta + Ts*inv(W_eta)*omega with gyro input.',
      ' F = d eta1/d eta (3x3), G = d eta1/d omega (3x3).'],
     [('eta1', eta1), ('F', F), ('G', G)],
     angles + [('omega1', 'omega(1)'), ('omega2', 'omega(2)'), ('omega3', 'omega(3)')])
emit('attitudeMeasurement', '[h, H] = attitudeMeasurement(eta, g_I, m_I)',
     ['ATTITUDEMEASUREMENT Accelerometer (xi_dd = 0) and magnetometer model.',
      ' h = [R_IB^T*(-g_I); R_IB^T*m_I] (6x1), H = dh/d eta (6x3).'],
     [('h', h), ('H', H)],
     angles + [(f'g_I{i}', f'g_I({i})') for i in (1, 2, 3)]
     + [(f'm_I{i}', f'm_I({i})') for i in (1, 2, 3)])
